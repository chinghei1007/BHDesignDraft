function splitSelectors(value) {
  let result = [],
    start = 0,
    depth = 0,
    quote = "";
  for (let i = 0; i < value.length; i++) {
    const c = value[i];
    if (quote) {
      if (c === quote && value[i - 1] !== "\\") quote = "";
      continue;
    }
    if (c === '"' || c === "'") {
      quote = c;
      continue;
    }
    if (c === "(" || c === "[") depth++;
    else if (c === ")" || c === "]") depth--;
    else if (c === "," && depth === 0) {
      result.push(value.slice(start, i).trim());
      start = i + 1;
    }
  }
  result.push(value.slice(start).trim());
  return result;
}
function exportRules(rules, ui, noColor = false) {
  let output = "";
  for (const rule of rules) {
    if (rule.type === CSSRule.STYLE_RULE) {
      let selected = splitSelectors(rule.selectorText).filter((selector) => {
        if (!/(^|[^\w-])\.ui(?=[\s.#:[>+~,{]|$)/.test(selector)) return false;
        let test = selector
          .replace(/::[\w-]+/g, "")
          .replace(/:(hover|focus|focus-visible|active)(?![\w-])/g, "");
        try {
          return ui.matches(test) || !!ui.querySelector(test);
        } catch (e) {
          return false;
        }
      });
      if (selected.length) {
        const declarations = noColor
          ? withoutColors(rule.style)
          : rule.style.cssText;
        if (declarations)
          output += selected.join(", ") + " { " + declarations + " }\n";
      }
    } else if (rule.type === CSSRule.MEDIA_RULE) {
      let inner = exportRules(rule.cssRules, ui, noColor);
      if (inner)
        output += "@media " + rule.conditionText + " {\n" + inner + "}\n";
    }
  }
  return output;
}
function withoutColors(style) {
  const clean = document.createElement("span").style;
  for (let i = 0; i < style.length; i++) {
    const prop = style[i],
      value = style.getPropertyValue(prop),
      priority = style.getPropertyPriority(prop);
    if (
      prop.startsWith("--") &&
      !/^(--ed-|--editor-gap$|--list-(marker|size|weight|padding|radius)$)/.test(
        prop,
      )
    )
      continue;
    if (
      /(^|-)color$|^color$|^background|^box-shadow$|^text-shadow$|^fill$|^stroke$|^caret-color$|^accent-color$|^outline$|^border-(top|right|bottom|left)-color$/.test(
        prop,
      )
    )
      continue;
    if (/^border(?:-(?:top|right|bottom|left))?$/.test(prop)) {
      for (const suffix of ["width", "style"]) {
        const name = prop + "-" + suffix,
          v = style.getPropertyValue(name);
        if (v) clean.setProperty(name, v, priority);
      }
      continue;
    }
    if (/^(border-image|text-decoration)$/.test(prop)) continue;
    clean.setProperty(prop, value, priority);
  }
  return clean.cssText;
}
function pathFor(el, root) {
  let steps = [];
  while (el && el !== root) {
    let pos = Array.prototype.indexOf.call(el.parentElement.children, el) + 1;
    steps.unshift(el.tagName.toLowerCase() + ":nth-child(" + pos + ")");
    el = el.parentElement;
  }
  return ".ui > " + steps.join(" > ");
}

export function generateCss({
  page,
  colorsDisabled,
  elementSettings,
  headingSettings,
}) {
  const ui = page.querySelector(".ui"),
    computed = getComputedStyle(ui),
    classes = [...ui.classList].join(" ");
  let css =
    '/* Generated by the design playground for Tailwind CSS v4.\n   Preview markup root class="' +
    classes +
    '".\n   Integrate with existing application styles and layout imports as needed.\n*/\n\n@import "tailwindcss";\n\n';
  css += "/* Design tokens */\n:root {\n";
  for (const prop of computed) {
    if (prop.startsWith("--")) {
      const value = computed.getPropertyValue(prop).trim();
      if (value) css += "  " + prop + ": " + value + ";\n";
    }
  }
  css +=
    "  --primary: var(--accent);\n  --primary-bg: var(--soft);\n  --secondary: var(--nav);\n  --secondary-bg: var(--bg);\n  --header: var(--nav);\n  --gray-text: var(--auto-page-text, var(--ink));\n  --font-family: " +
    computed.fontFamily +
    ";\n}\n\n";
  css +=
    "@theme {\n  --color-primary: var(--primary);\n  --color-primary-bg: var(--primary-bg);\n  --color-secondary: var(--secondary);\n  --color-secondary-bg: var(--secondary-bg);\n  --color-header: var(--header);\n  --color-gray-text: var(--gray-text);\n  --font-sans: var(--font-family);\n}\n\n";
  const savedStyles = elementSettings || {},
    headingColors = headingSettings || {};
  const targets = savedStyles.targets || {},
    modes = {
      all: [""],
      horizontal: ["left", "right"],
      vertical: ["top", "bottom"],
      top: ["top"],
      right: ["right"],
      bottom: ["bottom"],
      left: ["left"],
    };
  function spacingDeclarations(prop, value) {
    let map =
        value && typeof value === "object"
          ? value
          : value
            ? { all: value }
            : {},
      out = "";
    for (const [mode, sides] of Object.entries(modes))
      for (const side of sides) {
        let val = map[mode];
        let name = prop + (side ? "-" + side : "");
        if (val && CSS.supports(name, val))
          out += "  " + name + ": " + val + ";\n";
      }
    return out;
  }
  function headingRule(level, defaultSize) {
    const name = "heading-" + level,
      t = targets[name] || {};
    let out =
      "h" +
      level +
      " {\n  @apply font-bold;\n  color: " +
      (headingColors[name] || "var(--gray-text)") +
      ";\n  font-size: " +
      (t.size || defaultSize) +
      ";\n";
    if (t.font && CSS.supports("font-family", t.font))
      out += "  font-family: " + t.font + ";\n";
    if (t.lineHeight && CSS.supports("line-height", t.lineHeight))
      out += "  line-height: " + t.lineHeight + ";\n";
    return (
      out +
      spacingDeclarations("padding", t.padding) +
      spacingDeclarations("margin", t.margin) +
      "}\n\n"
    );
  }
  css +=
    "/* Shared base styles */\n* { box-sizing: border-box; }\nhtml { min-height: 100%; background: var(--bg); }\nbody { @apply m-0 min-h-screen font-sans; color: var(--gray-text); background: var(--bg); }\na { color: inherit; text-decoration: none; }\nbutton { font: inherit; }\n\n";
  css +=
    headingRule(1, "var(--ed-3xl)") +
    headingRule(2, "var(--ed-lg)") +
    headingRule(3, "var(--ed-xl)") +
    headingRule(4, "var(--ed-lg)") +
    headingRule(5, "var(--ed-base)");
  const body = targets.body || {};
  css += "p {\n  font-size: " + (body.size || "var(--ed-base)") + ";\n";
  if (body.font && CSS.supports("font-family", body.font))
    css += "  font-family: " + body.font + ";\n";
  if (body.lineHeight && CSS.supports("line-height", body.lineHeight))
    css += "  line-height: " + body.lineHeight + ";\n";
  css +=
    spacingDeclarations("padding", body.padding) +
    spacingDeclarations("margin", body.margin) +
    "}\n\n";
  const card = ui.querySelector(".panel"),
    btn = ui.querySelector(".cta"),
    cardStyle = card && getComputedStyle(card),
    componentRules = page.querySelector(".component-style-rules"),
    savedRules = componentRules.textContent;
  let btnStyle = null;
  if (btn) {
    componentRules.textContent = savedRules
      .split("\n")
      .filter((line) => !line.includes(" > "))
      .join("\n");
    let style = getComputedStyle(btn);
    btnStyle = Object.fromEntries(
      [
        "backgroundColor",
        "color",
        "borderRadius",
        "padding",
        "fontSize",
        "fontWeight",
        "border",
      ].map((key) => [key, style[key]]),
    );
    componentRules.textContent = savedRules;
  }
  css +=
    "/* Shared components (adapt selectors to the target application) */\n";
  if (cardStyle)
    css +=
      ".block { @apply border; background: " +
      cardStyle.backgroundColor +
      "; border-color: " +
      cardStyle.borderColor +
      "; border-radius: " +
      cardStyle.borderRadius +
      "; padding: " +
      cardStyle.padding +
      "; }\n";
  if (btnStyle)
    css +=
      ".btn-primary { @apply cursor-pointer; background: " +
      btnStyle.backgroundColor +
      "; color: " +
      btnStyle.color +
      "; border: " +
      btnStyle.border +
      "; border-radius: " +
      btnStyle.borderRadius +
      "; padding: " +
      btnStyle.padding +
      "; font-size: " +
      btnStyle.fontSize +
      "; font-weight: " +
      btnStyle.fontWeight +
      "; }\n";
  css += "\n";
  css += "/* Template components and responsive layout */\n";
  for (const sheet of document.styleSheets) {
    if (
      sheet.ownerNode.classList.contains("element-style-rules") ||
      sheet.ownerNode.classList.contains("component-style-rules") ||
      sheet.ownerNode.classList.contains("shadow-style-rules") ||
      sheet.ownerNode.classList.contains("table-style-rules") ||
      sheet.ownerNode.classList.contains("footer-style-rules")
    )
      continue;
    try {
      css += exportRules(sheet.cssRules, ui);
    } catch (e) {}
  }
  css +=
    "\n/* Current design defaults and settings */\n" +
    [...ui.classList].map((name) => "." + CSS.escape(name)).join("") +
    " { font-family: " +
    computed.fontFamily +
    ";";
  for (const prop of computed) {
    if (prop.startsWith("--")) {
      const value = computed.getPropertyValue(prop).trim();
      if (value) css += " " + prop + ": " + value + ";";
    }
  }
  css += " }\n";
  ui.querySelectorAll("[style]").forEach((el) => {
    if (el.style.length)
      css += pathFor(el, ui) + " { " + el.style.cssText + " }\n";
  });
  const overrides = page.querySelector(".element-style-rules").textContent;
  css +=
    "\n/* Custom typography and corner radii */\n" +
    overrides.replace(/\.ui\[data-element-editor="\d+"\]/g, ".ui");
  const components = page.querySelector(".component-style-rules").textContent;
  css +=
    "\n/* Custom button and navigation styles */\n" +
    components.replace(/\.ui\[data-component-editor="\d+"\]/g, ".ui");
  if (colorsDisabled) {
    css =
      '/* Tailwind v4 template export: color scheme disabled.\n   Preview markup root class="' +
      classes +
      '".\n*/\n\n@import "tailwindcss";\n\n:root {\n';
    for (const prop of computed) {
      if (
        /^(--ed-|--editor-gap$|--list-(marker|size|weight|padding|radius)$)/.test(
          prop,
        )
      ) {
        const value = computed.getPropertyValue(prop).trim();
        if (value) css += "  " + prop + ": " + value + ";\n";
      }
    }
    css +=
      "  --font-family: " +
      computed.fontFamily +
      ";\n}\n\n@theme { --font-sans: var(--font-family); }\n\n";
    css +=
      "* { box-sizing: border-box; }\nbody { @apply m-0 min-h-screen font-sans; }\nbutton { font: inherit; }\n\n";
    for (let level = 1; level <= 5; level++) {
      const name = "heading-" + level,
        t = targets[name] || {},
        defaults = [
          "var(--ed-3xl)",
          "var(--ed-lg)",
          "var(--ed-xl)",
          "var(--ed-lg)",
          "var(--ed-base)",
        ];
      css +=
        "h" +
        level +
        " { @apply font-bold; font-size: " +
        (t.size || defaults[level - 1]) +
        ";";
      if (t.font && CSS.supports("font-family", t.font))
        css += " font-family: " + t.font + ";";
      if (t.lineHeight && CSS.supports("line-height", t.lineHeight))
        css += " line-height: " + t.lineHeight + ";";
      css +=
        "\n" +
        spacingDeclarations("padding", t.padding) +
        spacingDeclarations("margin", t.margin) +
        "}\n";
    }
    css += "p { font-size: " + (body.size || "var(--ed-base)") + ";";
    if (body.font && CSS.supports("font-family", body.font))
      css += " font-family: " + body.font + ";";
    if (body.lineHeight && CSS.supports("line-height", body.lineHeight))
      css += " line-height: " + body.lineHeight + ";";
    css +=
      "\n" +
      spacingDeclarations("padding", body.padding) +
      spacingDeclarations("margin", body.margin) +
      "}\n";
    if (cardStyle)
      css +=
        ".block { border-width: " +
        cardStyle.borderWidth +
        "; border-style: " +
        cardStyle.borderStyle +
        "; border-radius: " +
        cardStyle.borderRadius +
        "; padding: " +
        cardStyle.padding +
        "; }\n";
    if (btnStyle)
      css +=
        ".btn-primary { @apply cursor-pointer; border-width: " +
        btnStyle.border.split(" ")[0] +
        "; border-style: " +
        (btnStyle.border.includes("solid") ? "solid" : "none") +
        "; border-radius: " +
        btnStyle.borderRadius +
        "; padding: " +
        btnStyle.padding +
        "; font-size: " +
        btnStyle.fontSize +
        "; font-weight: " +
        btnStyle.fontWeight +
        "; }\n";
    for (const sheet of document.styleSheets) {
      if (
        [
          "color-scheme-toggle-style",
          "element-style-rules",
          "component-style-rules",
          "shadow-style-rules",
          "table-style-rules",
          "footer-style-rules",
        ].some((name) => sheet.ownerNode.classList.contains(name))
      )
        continue;
      try {
        css += exportRules(sheet.cssRules, ui, true);
      } catch (e) {}
    }
    css +=
      "\n/* Current layout typography */\n" +
      [...ui.classList].map((name) => "." + CSS.escape(name)).join("") +
      " { font-family: " +
      computed.fontFamily +
      "; }\n";
    ui.querySelectorAll("[style]").forEach((el) => {
      let clean = withoutColors(el.style);
      if (clean) css += pathFor(el, ui) + " { " + clean + " }\n";
    });
    for (const name of [
      "element-style-rules",
      "component-style-rules",
      "shadow-style-rules",
      "table-style-rules",
      "footer-style-rules",
    ]) {
      const sheet = page.querySelector("." + name).sheet;
      if (sheet) css += exportRules(sheet.cssRules, ui, true);
    }
    css = css.replace(
      /\.ui\[data-(?:element|component)-editor="\d+"\]/g,
      ".ui",
    );
  }
  if (!colorsDisabled) {
    for (const cls of [
      "shadow-style-rules",
      "table-style-rules",
      "footer-style-rules",
    ]) {
      const style = page.querySelector("." + cls);
      css +=
        "\n/* " +
        (cls === "shadow-style-rules"
          ? "Container shadows"
          : cls === "table-style-rules"
            ? "Table preview"
            : "Footer") +
        " */\n" +
        style.textContent.replace(
          /\.ui\[data-(?:shadow|table|footer)-editor="\d+"\]/g,
          ".ui",
        );
    }
  } else
    css = css.replace(
      /\.ui\[data-(?:shadow|table|footer)-editor="\d+"\]/g,
      ".ui",
    );
  return css;
}

export function downloadCss(css) {
  const blob = new Blob([css], { type: "text/css;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = "App.css";
  document.body.append(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
